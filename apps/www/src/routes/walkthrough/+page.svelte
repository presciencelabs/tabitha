<h1>One verse, every step</h1>
<p class="page-dek">
	Acts 10:9, traced through the whole pipeline — the people who touch it and the shape the text
	takes at each stage.
</p>

<div class="page-body">
	<p>
		<a href="/workflows">Workflows</a> and <a href="/how-it-works">How does it work?</a> describe
		this process in the abstract. Here's what it actually looks like on a real verse, start to
		finish.
	</p>

	<ol class="walkthrough-steps">
		<li class="step">
			<span class="step-number">1</span>
			<div>
				<h2>Source</h2>
				<p>
					The starting point is the source text alongside translator's notes drawn from
					established Scripture resources — spelling out what the source leaves implicit.
				</p>
				<blockquote class="example-quote">
					About noon the next day those [three men] were traveling [along the road] and were
					coming near the city [of Joppa].
				</blockquote>
			</div>
		</li>

		<li class="step">
			<span class="step-number">2</span>
			<div>
				<h2>Draft</h2>
				<p>
					A drafter writes a first plain-English semantic paraphrase, bracketing the implicit
					information the source text leaves unsaid.
				</p>
				<blockquote class="example-quote">
					On the next day at about noon [when those people already were near Joppa] Peter go-up to
					the roof of the house [that Peter was staying at] [in-order-to] pray.
				</blockquote>
			</div>
		</li>

		<li class="step">
			<span class="step-number">3</span>
			<div>
				<h2>Review</h2>
				<p>
					A reviewer and a checker — with Old and New Testament specialists weighing in — refine
					the draft together until they agree it faithfully carries the meaning, alongside a
					plain-language backtranslation for a final sanity check.
				</p>
			</div>
		</li>

		<li class="step">
			<span class="step-number">4</span>
			<div>
				<h2>Encode</h2>
				<p>
					The signed-off draft is parsed into the system's formal semantic representation,
					flagged for anything ambiguous or incomplete until it checks out clean.
				</p>
				<blockquote class="example-notation">
					[NP Peter(N)] [VP see-D(V)] [NP dream/vision(N)] . ] | [C [NP at-B(Adp) [AdjP about(Adj)]
					noon(N)] [NP Peter(N)] [VP go-up(V)] [NP roof(N) [NP -Part Whole(Adp) house(N)]] [NP
					on-E(Adp) [AdjP next(Adj)] day(N)] [C when(Adp) [NP person(N)] [VP be-F(V)]] [NP near(Adp)
					Joppa(N)] [AdvP already(Adv)]] [C in-order-to(Adp) [NP Peter(N)] [VP pray(V)]] . ]
				</blockquote>
			</div>
		</li>

		<li class="step">
			<span class="step-number">5</span>
			<div>
				<h2>Generate</h2>
				<p>
					That same representation — shared across every target language — drives a target
					language's own lexicon and grammar rules to produce a full draft, ready for a native
					speaker to take from there.
				</p>
			</div>
		</li>
	</ol>

	<p>
		This walks through the conventional path start to finish. See <a href="/workflows">Workflows</a>
		for how an AI assistant can shorten the drafting step.
	</p>
</div>

