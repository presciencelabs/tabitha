<h1>Workflows</h1>
<p class="page-dek">
	The same pipeline runs underneath either way — what changes is how much of the analysis work a
	person has to do by hand first.
</p>

<div class="page-body">
	<h2>Without AI assistance</h2>
	<p>
		A linguist works through the source text passage by passage, building its semantic
		representation entirely by hand: identifying the underlying concepts, marking the features
		that matter for the target language, and resolving ambiguity the source language leaves open.
		A compatibility checker flags anything the target lexicon doesn't yet support, so gaps get
		caught before they reach generation rather than after. Once a passage's representation is
		solid, the transfer and synthesizing grammars generate a draft, and a native speaker reviews
		and refines it into something that actually reads naturally.
	</p>

	<h2>With AI assistance</h2>
	<p>
		The same steps happen, but an AI assistant built into the editor drafts the first pass at the
		semantic representation — proposing concepts, features, and structure for a linguist to
		confirm, correct, or override rather than build from scratch. The compatibility check,
		generation, and native-speaker review stay exactly the same; what shrinks is the hours spent on
		the initial encoding, which is usually the slowest step in the whole process.
	</p>

	<p>
		Either way, nothing reaches a translation team without a native speaker's review — the
		software drafts, it doesn't decide. See <a href="/how-it-works">How does it work?</a> for what
		each of these stages is actually doing underneath.
	</p>
</div>

