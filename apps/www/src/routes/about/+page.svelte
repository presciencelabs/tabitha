<h1>About</h1>
<p class="page-dek">
	Built by linguists, for the languages that don't yet have a Bible translation of their own.
</p>

<div class="page-body">
	<p>
		TaBiThA started from a simple observation: producing a first translation of Scripture into a
		minority language takes a small team of people years of painstaking, specialized work — and
		for many of the languages that need one most, that team and that time have never been
		available. The software exists to change that ratio, not to replace the translators, but to
		give them a real head start and let them spend their time on the part that actually needs a
		human: making the translation sound right in their own language.
	</p>
	<p>
		The project is <a href="https://www.canil.ca">CanIL</a>'s research and innovation arm. It's
		open source — the full history of decisions, the code, and the data are all public, at
		<a href="https://github.com/presciencelabs/tabitha">github.com/presciencelabs/tabitha</a>.
	</p>

